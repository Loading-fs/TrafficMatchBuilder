using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security;
using System.Text;
using TrafficMatchBuilder.Models;

namespace TrafficMatchBuilder.Services;

public sealed class VmrExporter
{
    public void Export(string filePath, IEnumerable<AircraftEntry> entries)
    {
        var usableEntries = entries
            .Where(entry => entry.IsExportable)
            .GroupBy(entry => new { entry.Title, entry.TypeCode, Code = entry.ExportCode })
            .Select(group => group.First())
            .OrderBy(entry => entry.TypeCode)
            .ThenBy(entry => entry.ExportCode)
            .ThenBy(entry => entry.Title)
            .ToList();

        var sb = new StringBuilder();

        sb.AppendLine(@"<?xml version=""1.0"" encoding=""utf-8""?>");
        sb.AppendLine(@"<ModelMatchRuleSet>");
        sb.AppendLine(@"  <!-- Generated by TrafficMatch Builder v0.6 Beta -->");

        foreach (var entry in usableEntries)
        {
            var typeCode = Escape(entry.TypeCode);
            var modelName = Escape(entry.Title);
            var code = Escape(entry.ExportCode);

            if (!string.IsNullOrWhiteSpace(code))
                sb.AppendLine($@"  <ModelMatchRule CallsignPrefix=""{code}"" TypeCode=""{typeCode}"" ModelName=""{modelName}"" />");
            else
                sb.AppendLine($@"  <ModelMatchRule TypeCode=""{typeCode}"" ModelName=""{modelName}"" />");
        }

        sb.AppendLine(@"</ModelMatchRuleSet>");

        File.WriteAllText(filePath, sb.ToString(), Encoding.UTF8);
    }

    private static string Escape(string value) => SecurityElement.Escape(value) ?? "";
}
